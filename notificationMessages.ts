/**
 * Get daily notification based on current day of month (1-31)
 */
export function getDailyNotification(date: Date = new Date(), memberName?: string): { title: string; body: string; theme: string } {
  const day = date.getDate(); // 1 to 31
  if (day === 1) {
    const monthly = getMonthlySavingsNotification(memberName);
    return {
      title: monthly.title,
      body: monthly.body,
      theme: 'মাসিক সঞ্চয় জমা'
    };
  }

  const found = DAILY_NOTIFICATIONS.find(m => m.day === day) || DAILY_NOTIFICATIONS[1];
  return {
    title: found.title,
    body: found.body,
    theme: found.theme
  };
}
